// Run: node scripts/gen-emoji-assets.mjs
// Downloads Twemoji PNGs for every emoji used as a logo preset and emits
// src/qr/emoji-assets.ts as a { codepoint: base64 } map — bundled offline,
// no CDN / no expo-asset needed.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT = resolve(ROOT, "src/qr/emoji-assets.ts");

const TWEMOJI = "https://cdnjs.cloudflare.com/ajax/libs/twemoji/14.0.2/72x72/";

// Must stay in sync with src/qr/presets.ts FREE_LOGO_PRESETS.
const EMOJIS = [
  "🏥","🦷","💊","🐾","☕","🍽️","🍕","🍣","🍔","🍺","🎂","💈","💅","🏋️",
  "🧘","🏨","🚗","🛍️","🏦","⚖️","🎓","🏗️","🌸","🎵","📷","🐕","👑","🚀",
  "⚡","👁️","🚕","✈️","🏠","🔑","🎁","❤️","⭐","🔥","🐱","🎯",
];

function codepoint(emoji) {
  return Array.from(emoji)
    .map((c) => c.codePointAt(0).toString(16))
    .filter((h) => h !== "fe0f")
    .join("-");
}

const map = {};
const missing = [];
for (const emoji of EMOJIS) {
  const cp = codepoint(emoji);
  const url = `${TWEMOJI}${cp}.png`;
  try {
    const res = await fetch(url);
    if (!res.ok) { missing.push(`${emoji} (${cp}) -> ${res.status}`); continue; }
    const buf = Buffer.from(await res.arrayBuffer());
    map[cp] = buf.toString("base64");
  } catch (e) {
    missing.push(`${emoji} (${cp}) -> ${e}`);
  }
}

const body = Object.entries(map)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");

const src = `// AUTO-GENERATED by scripts/gen-emoji-assets.mjs — do not edit.
// Twemoji 14.0.2, 72×72 PNG, base64 (no data: prefix). Bundled for offline use.
export const EMOJI_ASSETS: Record<string, string> = {
${body}
};
`;

writeFileSync(OUT, src, "utf8");
console.log(`Wrote ${OUT} (${Object.keys(map).length} emojis, ${Math.round(src.length / 1024)} KB)`);
if (missing.length) console.log("Missing:\n" + missing.join("\n"));
